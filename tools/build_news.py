"""Converts a Telegram channel HTML export into assets/js/news.js.

Usage:  python tools/build_news.py [exportoftgchatRSS.html]
Re-run after each new export; newest posts come first on the site.
"""
import html
import json
import re
import sys

CHANNEL = "https://t.me/rusport_org"
SIGNATURE = "Русское спортивное общество – объединяем тех"
SKIP_IF_CONTAINS = ["ЖЮРИ ПРЕМИИ"]  # long jury lists aren't useful as site news

src = sys.argv[1] if len(sys.argv) > 1 else "exportoftgchatRSS.html"
doc = open(src, encoding="utf-8").read()

def clean(fragment):
    t = re.sub(r"<br\s*/?>", "\n", fragment)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.unescape(t)
    t = t.split(SIGNATURE)[0]
    return re.sub(r"\n{3,}", "\n\n", t).strip()

def tag_for(text):
    low = text.lower()
    head = low.splitlines()[0]
    if "технология дня" in low: return "Технологии"
    if "история" in head or "кейс" in low[:200]: return "Кейсы"
    if "регистрация" in low or "премия" in head: return "События"
    if any(w in low for w in ("исследован", "данным", "млрд", "%")): return "Аналитика"
    if "курс" in low or "обучени" in low: return "Обучение"
    return "Индустрия"

items = []
for m in re.finditer(r'<div class="message default clearfix" id="message(\d+)">(.*?)(?=<div class="message (?:default|service))', doc + '<div class="message service', re.S):
    mid, block = m.groups()
    date = re.search(r'date details" title="(\d\d)\.(\d\d)\.(\d{4})', block)
    text = re.search(r'<div class="text">(.*?)</div>', block, re.S)
    if not (date and text):
        continue
    body = clean(text.group(1))
    if len(body) < 120 or any(s in body for s in SKIP_IF_CONTAINS):
        continue
    deco = " 😮💡💼📣🔝"
    raw = body.split("\n")
    first = next(i for i, l in enumerate(raw) if l.strip(deco))
    title = raw[first].strip(deco)
    text = "\n".join(raw[first + 1:]).strip()
    rest = [l.strip(deco) for l in raw[first + 1:] if l.strip(deco)]
    if title.upper() == "ТЕХНОЛОГИЯ ДНЯ" and rest:
        title = "Технология дня: " + next((l for l in rest if not l.startswith("Вдохнов")), rest[0])
    d, mo, y = date.groups()
    items.append({
        "id": int(mid),
        "date": f"{y}-{mo}-{d}",
        "tag": tag_for(body),
        "title": title.rstrip("."),
        "text": text,
        "url": f"{CHANNEL}/{mid}",
    })

items.sort(key=lambda x: (x["date"], x["id"]), reverse=True)
with open("assets/js/news.js", "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_news.py — do not edit by hand\n")
    f.write("window.RSO_NEWS = " + json.dumps(items, ensure_ascii=False, indent=1) + ";\n")
print(f"{len(items)} posts -> assets/js/news.js")
